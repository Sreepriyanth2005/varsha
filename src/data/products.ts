export const featuredProducts = products.filter((p) => p.isFeatured)
export const consumerProducts = products.filter((p) => !p.isSpecialtyChemical)
export const specialtyProducts = products.filter((p) => p.isSpecialtyChemical)

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug)
}

export function getRelatedProducts(product: Product, count = 3): Product[] {
  return products
    .filter((p) => p.id !== product.id && p.categorySlug === product.categorySlug)
    .slice(0, count)
}
